"""Reproduce a judgment-based screen; outputs are not probabilities or valuations."""

import argparse
import copy
import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
AXES = "HTKV"
STATUSES = {"compare", "benchmark", "high_burden", "result_pending", "claim_hold", "analysis_hold"}


def validate(model):
    rows = model["candidates"]
    if len(rows) != model["candidate_count"] or len({r["key"] for r in rows}) != len(rows):
        raise ValueError("Candidate count or unique identity mismatch")
    for weights in model["weights_percent"].values():
        if set(weights) != set(AXES) or sum(weights.values()) != 100 or min(weights.values()) < 0:
            raise ValueError("Invalid weights")
    for row in rows:
        if row["status"] not in STATUSES or set(row["scores"]) != set(AXES):
            raise ValueError(f"Invalid status or dimensions: {row['key']}")
        for values in row["scores"].values():
            if len(values) != 3 or values != sorted(values) or any(type(v) is not int or not 0 <= v <= 4 for v in values):
                raise ValueError(f"Invalid score range: {row['key']}")
        for field in ("technical_cost_kusd", "months"):
            values = row[field]
            if len(values) != 3 or values != sorted(values) or min(values) <= 0:
                raise ValueError(f"Invalid planning range: {row['key']}")
        if not (ROOT / row["dossier"]).is_file():
            raise ValueError(f"Missing dossier: {row['key']}")


def score(row, weights):
    # Integer numerator avoids floating-point tie artifacts.
    return sum(weights[axis] * row["scores"][axis][1] for axis in AXES)


def eligible(row):
    # This is only the conditional small-capital technical screen.
    return row["status"] == "compare" and row["scores"]["K"][1] >= 2


def ranks(rows, weights):
    scores = {r["key"]: score(r, weights) for r in rows}
    return {key: 1 + sum(other > value for other in scores.values()) for key, value in scores.items()}


def outputs(model):
    rows = model["candidates"]
    weights = model["weights_percent"]
    all_ranks = {name: ranks(rows, w) for name, w in weights.items()}
    bounded = [r for r in rows if eligible(r)]
    bounded_ranks = {name: ranks(bounded, w) for name, w in weights.items()}
    ordered = sorted(rows, key=lambda r: (-score(r, weights["balanced"]), r["name"]))
    fields = ["candidate", "status", "conditional_capital_screen", "H", "T", "K", "V", "balanced_score",
              "balanced_raw_rank", "clinical_raw_rank", "capital_raw_rank", "bounded_balanced_rank",
              "bounded_clinical_rank", "bounded_capital_rank", "one_axis_raw_rank_min", "one_axis_raw_rank_max",
              "technical_low_kusd", "technical_base_kusd", "technical_high_kusd", "base_headroom_kusd",
              "months_low", "months_base", "months_high", "flag", "dossier"]
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fields, lineterminator="\n")
    writer.writeheader()
    table = ["# Reproducible screening matrix", "", "Generated by `python3 research/phase2-program/ranking-review/calculate.py` from [judgments](screening-model.json). Read the [method](method.md) and [interpretation](README.md). Scores are ordinal judgments, not probabilities. Raw ranks ignore status and capital eligibility deliberately; they are not recommendations. Equal scores receive equal competition ranks; alphabetical display within ties is not a preference.", "", "Technical costs are USD thousands, low/base/high, excluding the material items named in each dossier. Headroom is arithmetic against $500k, not available risk capital. All rank sensitivity holds other candidates central.", "", "| Raw rank | Candidate | H/T/K/V | Score | Small-capital rank | Clinical / capital raw rank | One-axis raw rank range | Technical cost $k | Base headroom $k | Status |", "|---:|---|---|---:|---:|---|---|---|---:|---|"]
    for row in ordered:
        key = row["key"]
        stress = [all_ranks["balanced"][key]]
        for axis in AXES:
            for value in (row["scores"][axis][0], row["scores"][axis][2]):
                varied = copy.deepcopy(row)
                varied["scores"][axis][1] = value
                case = [varied if r["key"] == key else r for r in rows]
                stress.append(ranks(case, weights["balanced"])[key])
        cost = row["technical_cost_kusd"]
        headroom = model["capital_usd"] / 1000 - cost[1]
        vals = dict(candidate=row["name"], status=row["status"], conditional_capital_screen=eligible(row),
                    balanced_score=f"{score(row, weights['balanced']) / 100:.2f}",
                    one_axis_raw_rank_min=min(stress), one_axis_raw_rank_max=max(stress),
                    technical_low_kusd=cost[0], technical_base_kusd=cost[1], technical_high_kusd=cost[2],
                    base_headroom_kusd=f"{headroom:g}", months_low=row["months"][0], months_base=row["months"][1],
                    months_high=row["months"][2], flag=row["flag"], dossier=row["dossier"])
        vals.update({a: "/".join(map(str, row["scores"][a])) for a in AXES})
        for name in weights:
            vals[name + "_raw_rank"] = all_ranks[name][key]
            vals["bounded_" + name + "_rank"] = bounded_ranks[name].get(key, "")
        writer.writerow(vals)
        central = "/".join(str(row["scores"][a][1]) for a in AXES)
        qualification = row['status'] + (": " + row['flag'] if row['flag'] else "")
        table.append(f"| {all_ranks['balanced'][key]} | [{row['name']}]({row['dossier']}) | {central} | {vals['balanced_score']} | {bounded_ranks['balanced'].get(key, '—')} | {all_ranks['clinical'][key]} / {all_ranks['capital'][key]} | {min(stress)}–{max(stress)} | {'/'.join(map(str, cost))} | {headroom:g} | {qualification} |")
    table += ["", "The conditional small-capital column includes `compare` candidates with central K≥2. A low-end K below 2 can remove a candidate from that set; a favorable K can admit a larger-capital reserve. Status holds persist even if a numerical score rises. The table's one-axis range is an unfiltered rank sensitivity, not an exhaustive uncertainty interval or an estimate of success.", ""]
    return {"screening-matrix.csv": buf.getvalue(), "screening-matrix.md": "\n".join(table)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate inputs and require generated files to be current")
    args = parser.parse_args()
    model = json.loads((ROOT / "screening-model.json").read_text())
    validate(model)
    for filename, content in outputs(model).items():
        path = ROOT / filename
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale output: {filename}")
        else:
            path.write_text(content)
    print(f"{'Checked' if args.check else 'Generated'} {len(model['candidates'])} candidate comparisons")


if __name__ == "__main__":
    main()
